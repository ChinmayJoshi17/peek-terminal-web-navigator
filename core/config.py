"""Centralized configuration via pydantic-settings."""

from pathlib import Path
from typing import Any, Literal, Optional

from dotenv import load_dotenv
from pydantic import Field, field_validator
from pydantic_settings import BaseSettings, SettingsConfigDict

load_dotenv()


class LLMSettings(BaseSettings):
    """LLM provider configuration."""

    model: str = Field(
        default="openai/gpt-oss-120b",
        description="LLM model identifier (e.g., openai/gpt-oss-120b)"
    )
    provider: Literal["groq", "openai", "ollama"] = Field(
        default="groq",
        description="LLM provider"
    )
    groq_api_key: str = Field(
        default="",
        description="API key for the LLM provider",
        validation_alias="GROQ_API_KEY",
    )

    @property
    def api_key(self) -> str:
        return self.groq_api_key
    temperature: float = Field(
        default=0.1,
        description="LLM temperature for response randomness"
    )
    max_retries: int = Field(
        default=3,
        description="Maximum number of LLM API retries"
    )
    timeout: int = Field(
        default=60,
        description="Timeout for LLM API requests in seconds"
    )

    @field_validator("groq_api_key")
    @classmethod
    def validate_api_key(cls, v: str, info: Any) -> str:
        provider = info.data.get("provider", "groq")
        if not v and provider in ["groq", "openai"]:
            raise ValueError(f"API key is required for {provider} provider")
        return v


class BrowserSettings(BaseSettings):
    """Browser configuration."""

    headless: bool = Field(
        default=False,
        description="Run browser in headless mode"
    )
    slow_mo: int = Field(
        default=300,
        description="Delay between browser operations in milliseconds"
    )
    viewport_width: int = Field(
        default=1280,
        description="Browser viewport width"
    )
    viewport_height: int = Field(
        default=800,
        description="Browser viewport height"
    )
    load_timeout: int = Field(
        default=30000,
        description="Page load timeout in milliseconds"
    )


class LoopSettings(BaseSettings):
    """Agent loop configuration."""

    max_steps: int = Field(
        default=15,
        description="Maximum number of loop iterations"
    )
    checkpoint_enabled: bool = Field(
        default=True,
        description="Enable checkpoint saving/restore"
    )
    checkpoint_dir: str = Field(
        default=".checkpoints",
        description="Directory for checkpoint files"
    )
    guardrail_enabled: bool = Field(
        default=True,
        description="Enable guardrail checks"
    )
    guardrail_max_history: int = Field(
        default=3,
        description="Maximum action history for guardrail checks"
    )
    guardrail_max_retries: int = Field(
        default=2,
        description="Maximum retries for same action on same element"
    )
class ECCSettings(BaseSettings):
    """ECC-specific configuration."""

    rich_ui: bool = Field(
        default=True,
        description="Enable rich UI output"
    )
    log_level: str = Field(
        default="INFO",
        description="Logging level (DEBUG, INFO, WARNING, ERROR)"
    )
    log_file: Optional[str] = Field(
        default=None,
        description="Path to log file"
    )
    enable_profiling: bool = Field(
        default=False,
        description="Enable performance profiling"
    )


class Settings(BaseSettings):
    """Application settings, combining all domain-specific settings."""

    model_config = SettingsConfigDict(
        env_file=".env",
        env_file_encoding="utf-8",
        case_sensitive=False,
        extra="ignore"
    )

    llm: LLMSettings = Field(default_factory=LLMSettings)
    browser: BrowserSettings = Field(default_factory=BrowserSettings)
    loop: LoopSettings = Field(default_factory=LoopSettings)
    ecc: ECCSettings = Field(default_factory=ECCSettings)

    @classmethod
    def load(cls) -> "Settings":
        """Load settings from environment and CLI overrides."""
        return cls()

    def save_env(self) -> None:
        """Save current settings to .env file for persistence."""
        env_path = Path(".env")

        with open(env_path, "w") as f:
            f.write(f"# Generated by nano-browser-agent settings\n")
            f.write(f"# Model config\n")
            f.write(f"LLM_MODEL={self.llm.model}\n")
            f.write(f"LLM_PROVIDER={self.llm.provider}\n")
            f.write(f"LLM_API_KEY={self.llm.api_key}\n")
            f.write(f"LLM_TEMPERATURE={self.llm.temperature}\n")
            f.write(f"\n# Browser config\n")
            f.write(f"BROWSER_HEADLESS={self.browser.headless}\n")
            f.write(f"BROWSER_SLOW_MO={self.browser.slow_mo}\n")
            f.write(f"\n# Loop config\n")
            f.write(f"LOOP_MAX_STEPS={self.loop.max_steps}\n")

    @classmethod
    def from_cli_args(cls, args) -> "Settings":
        """Create settings from parsed CLI arguments."""
        # Create base settings
        settings = cls.load()

        # Override based on CLI args if provided
        if hasattr(args, "model") and args.model:
            settings.llm.model = args.model
        if hasattr(args, "provider") and args.provider:
            settings.llm.provider = args.provider
        if hasattr(args, "api_key") and args.api_key:
            settings.llm.api_key = args.api_key
        if hasattr(args, "headless") and args.headless is not None:
            settings.browser.headless = args.headless
        if hasattr(args, "max_steps") and args.max_steps:
            settings.loop.max_steps = args.max_steps

        return settings


# Global settings instance
_settings: Optional[Settings] = None


def get_settings() -> Settings:
    """Get global settings instance, loading if not already loaded."""
    global _settings
    if _settings is None:
        _settings = Settings.load()
    return _settings


def reset_settings() -> None:
    """Reset global settings instance."""
    global _settings
    _settings = None